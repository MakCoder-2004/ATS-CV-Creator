import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtempSync } from 'node:fs'
import { rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('review centers the CV and reveals only the selected wording and human-readable sources', async () => {
  test.setTimeout(120000)
  const userData = mkdtempSync(join(tmpdir(), 'cv-tailor-review-ux-'))
  let app: Awaited<ReturnType<typeof electron.launch>> | undefined
  try {
    app = await electron.launch({ args: [join(process.cwd(), 'out/main/index.js')], env: { ...process.env, CV_TAILOR_TEST_USER_DATA_DIR: userData, CV_TAILOR_SCRIPTED_ANALYSIS: 'generation' } })
    const page = await app.firstWindow()
    await page.setViewportSize({ width: 1440, height: 900 })
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    await page.evaluate(async () => {
      await window.workbench.saveContact({ fullName: 'Zoë Candidate', headline: 'Software Engineer', email: 'zoe@example.test' })
      await window.workbench.saveSkill({ name: 'TypeScript', category: 'Programming' })
      for (let index = 1; index <= 12; index++) await window.workbench.saveExperience({ kind: 'employment', title: `Engineer ${index}`, organization: `Systems ${index}`, description: `Built dependable software at organization ${index}.` })
    })
    await page.getByRole('button', { name: 'Open saved jobs' }).click()
    await page.getByLabel('Job title').fill('Engineer')
    await page.getByLabel('Company').fill('Example Co')
    await page.getByLabel('Posting and requirements').fill('Build services with TypeScript.')
    await page.getByRole('button', { name: 'Save job' }).click()
    await page.getByRole('button', { name: 'Tailor CV', exact: true }).click()
    await page.getByRole('button', { name: 'Inspect outgoing data' }).click()
    const flow = page.getByRole('region', { name: 'Tailoring workflow' })
    await flow.getByRole('button', { name: 'Authorize and start this run' }).click()
    await flow.getByRole('button', { name: 'Generate tailored draft' }).click()
    const paper = page.getByRole('article', { name: 'Draft CV review layout' })
    await expect(paper).toBeVisible({ timeout: 20000 })
    await expect(paper).not.toContainText('Professional summary')
    await expect(paper).not.toContainText('Software Engineer')
    await expect(paper).not.toContainText('Certificates')
    await expect(page.getByText(/Review layout · spacing and pagination may differ/i)).toBeVisible()
    const inspector = page.getByRole('region', { name: 'Selected wording and sources' })
    await expect(inspector.getByRole('heading', { name: 'Review the wording' })).toBeVisible()
    const addEducation = paper.getByRole('button', { name: 'Add education' })
    await addEducation.click()
    const recordDialog = page.getByRole('dialog', { name: 'Add education' })
    await expect(recordDialog.getByLabel('Degree', { exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(addEducation).toBeFocused()
    await expect(page.locator('.draft-edit-list, .draft-edit-item')).toHaveCount(0)
    await expect(inspector).not.toContainText('"kind"')
    await expect(inspector).not.toContainText('"organization"')
    await expect(page.getByRole('region', { name: 'CV review' })).not.toContainText('Dispatched requests')
    const checklist = page.getByRole('region', { name: 'Review checklist' })
    await expect(checklist.getByRole('button', { name: 'Check page length' })).toBeVisible()
    expect((await paper.boundingBox())!.width).toBeGreaterThanOrEqual(560)
    const categories = page.getByRole('navigation', { name: 'Review detail categories' })
    const sourceCategory = categories.getByRole('button', { name: 'Sources', exact: true })
    const checksCategory = categories.getByRole('button', { name: /^Checks & options/ })
    await expect(sourceCategory).toHaveAttribute('aria-pressed', 'true')
    expect((await categories.boundingBox())!.height).toBeGreaterThan(160)
    await checksCategory.click()
    await expect(checksCategory).toHaveAttribute('aria-pressed', 'true')
    const checks = page.getByRole('region', { name: 'Review notes' })
    await expect(checks.getByRole('heading', { name: 'Checks & next steps' })).toBeVisible()
    await expect(checks.getByRole('heading', { name: 'Change the wording' })).toBeVisible()
    await expect(checks.getByRole('button', { name: 'Improve a whole section' })).toBeVisible()
    await expect(checks.getByRole('button', { name: 'Hide section options' })).toHaveCount(0)
    await checks.getByRole('button', { name: 'Improve a whole section' }).click()
    await expect(checks.getByRole('combobox', { name: 'Regeneration section' })).toBeVisible()
    await expect(checks.getByRole('combobox', { name: 'Regeneration scope' })).toBeVisible()
    await expect(checks.getByRole('button', { name: 'Review data for section regeneration' })).toBeVisible()
    await page.screenshot({ path: 'test-results/review-ux-checks-viewport.png' })
    await sourceCategory.click()
    await expect(page.getByRole('region', { name: 'Regeneration proposals' })).toHaveCount(0)
    const selectable = paper.getByRole('button', { name: /Review sources for Engineer/ })
    expect(await selectable.count()).toBeGreaterThan(1)
    await selectable.nth(1).focus()
    await page.keyboard.press('Enter')
    await expect(selectable.nth(1)).toHaveAttribute('aria-pressed', 'true')
    await expect(inspector).toContainText('Systems')
    await expect(inspector).not.toContainText('"kind"')
    await inspector.getByRole('button', { name: 'Edit wording' }).click()
    await inspector.getByRole('textbox', { name: 'Wording for this CV' }).fill('Built dependable services for this role.')
    await inspector.getByRole('button', { name: 'Save wording' }).click()
    await expect(paper.getByText('Built dependable services for this role.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Approve CV' })).toBeDisabled()
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.screenshot({ path: 'test-results/review-ux-light.png', fullPage: true })
    const context = page.getByRole('complementary', { name: 'Review details' })
    const showDetails = checklist.getByRole('button', { name: 'Show review details' })
    if (await showDetails.isVisible()) await showDetails.click()
    await expect(showDetails).toHaveCount(0)
    await context.getByRole('button', { name: 'Hide review details' }).click()
    await expect(context).not.toBeVisible()
    await expect(showDetails).toBeFocused()
    await showDetails.click()
    await expect(context).toBeVisible()
    const contextBox = (await context.boundingBox())!
    expect(contextBox.x).toBeGreaterThanOrEqual((await paper.boundingBox())!.x + (await paper.boundingBox())!.width)
    expect(contextBox.x + contextBox.width).toBeLessThanOrEqual(1440)
    expect(contextBox.width).toBeGreaterThanOrEqual(280)
    expect(contextBox.y).toBeGreaterThanOrEqual(0)
    expect(contextBox.y).toBeLessThan(900)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/review-ux-context-viewport.png' })
    await page.screenshot({ path: 'test-results/review-ux-context-light.png', fullPage: true })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.getByRole('button', { name: 'Use dark mode' }).click()
    await page.setViewportSize({ width: 760, height: 900 })
    await expect(paper).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await page.screenshot({ path: 'test-results/review-ux-dark-narrow.png', fullPage: true })
    await page.setViewportSize({ width: 375, height: 812 })
    await checklist.getByRole('button', { name: 'Show review details' }).click()
    const mobileDialog = page.getByRole('dialog', { name: 'Review details' })
    await expect(mobileDialog).toBeVisible()
    await mobileDialog.getByRole('button', { name: /^Checks & options/ }).click()
    await expect(mobileDialog.getByRole('heading', { name: 'Change the wording' })).toBeVisible()
    expect(await mobileDialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/review-ux-checks-mobile.png' })
    await page.keyboard.press('Escape')
    await expect(mobileDialog).not.toBeVisible()
    await expect(showDetails).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(await page.locator('.paper').evaluate(element => element.scrollHeight <= element.clientHeight + 1), 'Narrow CV content must expand the paper instead of being clipped').toBe(true)
    await paper.getByRole('heading', { name: 'Technical Skills' }).scrollIntoViewIfNeeded()
    const bar = await checklist.boundingBox()
    expect(bar!.y).toBeGreaterThanOrEqual(0)
    expect(bar!.y + bar!.height, 'Review actions must remain visible while reading the bottom of the CV').toBeLessThanOrEqual(812)
    await expect(checklist).toContainText('Page length needed')
    await expect(page.getByRole('button', { name: 'Check CV for issues' })).toBeVisible()
    const mobileEntry = paper.getByRole('button', { name: /Review sources for Engineer/ }).first()
    await mobileEntry.click()
    await expect(inspector.getByRole('heading', { name: 'Review the wording' })).toBeFocused()
    await inspector.getByRole('button', { name: 'Back to selected wording' }).click()
    await expect(mobileEntry).toBeFocused()
    await page.screenshot({ path: 'test-results/review-ux-dark-mobile.png', fullPage: true })
  } finally {
    await app?.close().catch(() => {})
    await rm(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 })
  }
})
