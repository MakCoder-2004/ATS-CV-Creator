    await expect(page.getByRole('article', { name: 'Draft CV preview' }).getByText('Systems Engineer')).toBeVisible()
    await expect(page.getByRole('article', { name: 'Draft CV preview' }).getByText('Senior Engineer', { exact: true })).toBeVisible()
    await expect(page.getByRole('article', { name: 'Draft CV preview' }).getByText('Local Systems', { exact: true })).toBeVisible()
    await expect(page.getByRole('article', { name: 'Draft CV preview' }).getByText(/20\d{2}/).first()).toBeVisible()
    const coverage = page.getByRole('complementary', { name: 'Run review' }).getByRole('region', { name: 'Selected wording and sources' })
    await expect(coverage).not.toContainText('"kind"')
    await coverage.getByText('How your experience matches this job').click()
    await expect(coverage.getByRole('heading', { name: 'Supported matches' })).toBeVisible()
    await expect(coverage).toContainText('TypeScript — supported by saved facts')
    await expect(coverage.getByRole('heading', { name: 'Qualifications to consider' })).toBeVisible()
    await expect(coverage).toContainText('Kubernetes — not found in your saved facts')
    await expect(coverage).toContainText('Cloud architecture — not found in your saved facts')
    await expect(coverage).toContainText('Automated checks can miss mistakes')
    const preview = page.getByRole('article', { name: 'Draft CV preview' })
    await expect(preview.locator('h2')).toHaveText(['Professional summary', 'Experience', 'Technical skills'])
    await expect(review.getByRole('button', { name: 'Approve CV' })).toBeDisabled()
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Settings' }).click()
    await page.getByRole('textbox', { name: 'OpenRouter model ID' }).fill('openai/gpt-4o-mini')
    await page.getByRole('button', { name: 'Save model' }).click()
    await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Tailor CV' }).click()
    await expect(page.getByRole('article', { name: 'Draft CV preview' })).toBeVisible()
    await page.getByRole('button', { name: 'Create another CV' }).click()
    await expect(page.getByRole('heading', { name: 'What OpenRouter receives' })).toBeVisible()
    await expect(page.getByText('openai/gpt-4o-mini')).toBeVisible()
    await page.getByRole('button', { name: 'Back to posting' }).click()
    await expect(page.getByRole('article', { name: 'Draft CV preview' })).toBeVisible()
    await page.getByRole('button', { name: 'Check page length' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Your CV uses/ })).toContainText(/page/, { timeout: 30000 })
    const report = await page.evaluate(jobId => window.workbench.getDocumentFitReport(jobId), await page.evaluate(() => window.workbench.listJobs().then(jobs => jobs[0].id)))
    expect(report?.actualPages).toBeGreaterThan(0)
    expect(report?.extractedText.join(' ')).toContain('Zoë Candidate')
    expect(report?.linkTargets).toContain('https://example.test/cv')
    const extractedOrder = ['PROFESSIONAL SUMMARY', 'EXPERIENCE', 'SKILLS'].map(name => report!.extractedText.findIndex(text => text.includes(name)))
    expect(extractedOrder.every((position, index) => position >= 0 && (index === 0 || position > extractedOrder[index - 1])), JSON.stringify({ extractedOrder, extractedText: report?.extractedText })).toBe(true)
    expect(report?.extractedText.join(' ')).not.toMatch(/\b(EDUCATION|PROJECTS|CERTIFICATES)\b/)
    expect(report?.targetPages).toBe(1)
    expect(report?.overflow).toBe(true)
    expect(report?.proposedCuts.length).toBeGreaterThan(0)
    const jobId = await page.evaluate(() => window.workbench.listJobs().then(jobs => jobs[0].id))
    const beforeCuts = await page.evaluate(id => window.workbench.getDraft(id), jobId)
    expect(beforeCuts?.revision).toBe(1)
    await page.getByRole('checkbox').first().check()
    await page.getByRole('button', { name: 'Apply selected cuts' }).click()
    expect(await page.evaluate(id => window.workbench.getDraft(id).then(value => value?.revision), jobId)).toBe(2)
    await expect(page.getByRole('status').filter({ hasText: /Your CV uses/ })).toContainText(/page/, { timeout: 30000 })
    await expect.poll(async () => page.evaluate(id => window.workbench.getDocumentFitReport(id).then(value => value?.actualPages), jobId), { timeout: 30000 }).toBeGreaterThan(0)
    expect(await page.evaluate(id => window.workbench.getDraft(id).then(value => value?.checkReport), jobId)).toBeUndefined()
    expect(await page.evaluate(id => window.workbench.approveDraft(id), jobId)).toMatchObject({ ok: false })
    const revisedReport = await page.evaluate(id => window.workbench.getDocumentFitReport(id), jobId)
    expect(revisedReport?.actualPages).toBeGreaterThan(0)
    expect(revisedReport?.documentHash).not.toBe(report?.documentHash)
    expect(await page.evaluate(id => window.workbench.getDraft(id).then(value => value?.revision), jobId)).toBe(2)
    const canonical = await page.evaluate(id => window.workbench.getCanonicalDocument(id), jobId)
    expect(canonical?.style).toMatchObject({ fontFamily: 'Arial', bodyPt: 11, pageSize: 'A4' })
    expect(canonical?.identity.links).toEqual([{ label: 'Portfolio', url: 'https://example.test/cv' }])
    const twoPageDraft = await page.evaluate(async id => {
      const consent = await window.workbench.prepareOutboundConsent(id)
      if (!consent.ok) throw new Error(consent.message)
      const accepted = await window.workbench.acceptOutboundConsent(consent.token, true, true)
      if (!accepted.ok) throw new Error(accepted.message)
      await window.workbench.startAnalysis(consent.token)
      return window.workbench.generateDraft(consent.token, 2)
    }, jobId)
    expect(twoPageDraft).toMatchObject({ ok: true, draft: { pageTarget: 2, revision: 3 } })
    const twoPageReport = await page.evaluate(id => window.workbench.measureDocument(id), jobId)
    expect(twoPageReport.targetPages).toBe(2)
    expect(twoPageReport.actualPages).toBeLessThanOrEqual(2)
    expect(await page.evaluate(id => window.workbench.approveDraft(id), jobId)).toMatchObject({ ok: true, draft: { approved: true, approval: { targetPages: 2 } } })
    expect(await page.evaluate(id => window.workbench.assertDraftExportable(id), jobId)).toMatchObject({ ok: true })
    await page.getByRole('button', { name: 'Check page length' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Your CV uses/ })).toContainText(/page/)
    await page.getByRole('button', { name: 'Check CV for issues' }).click()
    await expect(page.getByRole('navigation', { name: 'Tailoring phases' }).locator('[aria-current="step"]')).toHaveText(/Export/)
    await expect(page.getByRole('button', { name: 'Export editable DOCX' })).toBeVisible()
    await page.getByRole('button', { name: 'Use dark mode' }).click()
    await expect(page.getByRole('button', { name: 'Use dark mode' })).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByRole('article', { name: 'Approved CV preview' })).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(page.getByRole('article', { name: 'Approved CV preview' })).toHaveCSS('font-family', 'Arial, sans-serif')
    expect(await page.evaluate(id => window.workbench.assertDraftExportable(id), jobId)).toMatchObject({ ok: true })

    const docxPath = join(userData, 'Candidate - Northwind Labs - Fictional Systems Engineer.docx')
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); return true }, docxPath)
    const exportButton = page.getByRole('button', { name: 'Export editable DOCX' })
    await expect(exportButton).toBeVisible()
    const attemptsBeforeExport = await page.evaluate(() => window.workbench.getAnalysisUsage().then(value => value.attempts))
    await exportButton.click()
    await expect(page.getByRole('region', { name: 'CV review' }).getByRole('status').filter({ hasText: 'Editable DOCX saved' })).toContainText('Word may reflow text differently')
    expect(await page.evaluate(() => window.workbench.getAnalysisUsage().then(value => value.attempts))).toBe(attemptsBeforeExport)
    expect(existsSync(docxPath)).toBe(true)
    const parsedDocx = await extractCanonicalDocx(readFileSync(docxPath))
    const pdfReport = await page.evaluate(id => window.workbench.getDocumentFitReport(id), jobId)
    const canonicalDocument = await page.evaluate(id => window.workbench.getCanonicalDocument(id), jobId)
    const normalized = (values: string[]) => values.join(' ').replace(/[\s\p{P}\p{S}]+/gu, '').normalize('NFKC').toLowerCase()
    const pdfText = normalized(pdfReport!.extractedText), docxText = normalized(parsedDocx.text)
    const canonicalStrings = [canonicalDocument!.identity.name, canonicalDocument!.identity.headline ?? '', ...canonicalDocument!.identity.contact, ...canonicalDocument!.identity.links.map(link => link.label), ...canonicalDocument!.sections.flatMap(section => [section.name, ...section.entries.flatMap(entry => [entry.heading, entry.organization ?? '', entry.dates ?? '', entry.text, ...entry.links.map(link => link.label)])])].filter(Boolean)
    for (const value of canonicalStrings) { expect(docxText, `DOCX missing canonical content: ${value}`).toContain(normalized([value])); expect(pdfText, `PDF missing canonical content: ${value}`).toContain(normalized([value])) }
    for (const term of ['Zoë Candidate', 'Senior Engineer', 'Local Systems', 'PROFESSIONAL SUMMARY', 'EXPERIENCE', 'SKILLS']) { expect(pdfText).toContain(normalized([term])); expect(docxText).toContain(normalized([term])) }
    for (const value of [pdfText, docxText]) expect(value).not.toMatch(/education|projects|certificates/)
    const sectionOrder = ['professionalsummary', 'experience', 'skills']
    const ordered = (value: string) => sectionOrder.map(name => value.indexOf(name))
    expect(ordered(pdfText).every((at, index, all) => at >= 0 && (index === 0 || at > all[index - 1])), JSON.stringify({ order: ordered(pdfText), text: pdfText })).toBe(true)
    expect(ordered(docxText).every((at, index, all) => at >= 0 && (index === 0 || at > all[index - 1]))).toBe(true)
    for (const value of [pdfText, docxText]) {
      let cursor = 0
      for (const section of canonicalDocument!.sections) {
        let position = value.indexOf(normalized([section.name]), cursor)
        expect(position, `Missing/out-of-order section ${section.name}`).toBeGreaterThanOrEqual(cursor)
        cursor = position + normalized([section.name]).length
        for (const entry of section.entries) {
          const fields = [entry.heading, entry.dates ?? '', entry.organization ?? '', entry.text, ...entry.links.map(link => link.label)].filter(Boolean)
          for (const field of fields) {
            position = value.indexOf(normalized([field]), cursor)
            expect(position, `Missing/out-of-order field ${field} in ${section.name}`).toBeGreaterThanOrEqual(cursor)
            cursor = position + normalized([field]).length
          }
        }
      }
    }
    const canonicalLinks = [
      ...canonicalDocument!.identity.links,
      ...canonicalDocument!.sections.flatMap(section => section.entries.flatMap(entry => entry.links))
    ].map(link => `${link.label}\u0000${link.url}`).sort()
    expect(parsedDocx.links.map(link => `${link.label}\u0000${link.url}`).sort()).toEqual(canonicalLinks)
    expect(pdfReport!.links.map(link => `${link.label}\u0000${link.url}`).sort()).toEqual(canonicalLinks)
    expect(pdfReport!.linkTargets.sort()).toEqual(canonicalLinks.map(link => link.split('\u0000')[1]).sort())
    const existingContent = Buffer.from('pre-existing destination')
    writeFileSync(docxPath, existingContent)
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1, checkboxChecked: false }); return true })
    await exportButton.click()
    await expect(page.getByRole('region', { name: 'CV review' }).getByRole('status').filter({ hasText: 'DOCX export cancelled' })).toContainText('existing file was not changed')
    expect(readFileSync(docxPath)).toEqual(existingContent)
    await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0, checkboxChecked: false }); return true })
    await exportButton.click()
    await expect(page.getByRole('region', { name: 'CV review' }).getByRole('status').filter({ hasText: 'Editable DOCX saved' })).toContainText('Word may reflow text differently')
    expect((await extractCanonicalDocx(readFileSync(docxPath))).text).toEqual(parsedDocx.text)
    await app.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true, filePath: '' }); return true })
    const beforeCancel = readFileSync(docxPath)
    await exportButton.click()
    await expect(page.getByRole('region', { name: 'CV review' }).getByRole('status').filter({ hasText: 'DOCX export cancelled' })).toContainText('DOCX export cancelled')
    expect(readFileSync(docxPath)).toEqual(beforeCancel)
    const failurePath = join(userData, 'missing-folder', 'failure.docx')
    await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }); return true }, failurePath)
    await exportButton.click()
    await expect(page.getByRole('region', { name: 'CV review' }).getByRole('alert')).toContainText('Could not save the DOCX')
    expect(readFileSync(docxPath)).toEqual(beforeCancel)
    const noExtensionPath = join(userData, 'candidate-without-extension')
    await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }); return true }, noExtensionPath)
    await exportButton.click()
    await expect(page.getByRole('region', { name: 'CV review' }).getByRole('alert')).toContainText('ending in .docx')
    expect(existsSync(noExtensionPath)).toBe(false)
    expect(existsSync(`${noExtensionPath}.docx`)).toBe(false)

    await app.close()
    app = await electron.launch({ args: [join(process.cwd(), 'out/main/index.js')], timeout: 60000, env: { ...process.env, CV_TAILOR_TEST_USER_DATA_DIR: userData, CV_TAILOR_SCRIPTED_ANALYSIS: 'generation' } })
    page = await app.firstWindow()
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    await page.getByRole('button', { name: /Fictional Systems Engineer/ }).click()
    expect(await page.evaluate(id => window.workbench.getDraft(id).then(value => ({ approved: value?.approved, approval: value?.approval?.contentHash })), jobId)).toMatchObject({ approved: true, approval: expect.any(String) })
    expect(await page.evaluate(id => window.workbench.assertDraftExportable(id), jobId)).toMatchObject({ ok: true })
    const staleDestination = join(userData, 'stale-dialog.docx')
    await app.evaluate(({ dialog }, destination) => {
      const globals = globalThis as typeof globalThis & { docxDialogReady?: boolean; resolveDocxDialog?: () => void }
      globals.docxDialogReady = false
      dialog.showSaveDialog = async () => await new Promise(resolve => { globals.docxDialogReady = true; globals.resolveDocxDialog = () => resolve({ canceled: false, filePath: destination }) })
      return true
    }, staleDestination)
    const pendingExport = page.evaluate(id => window.workbench.exportDraftDocx(id), jobId)
    await expect.poll(() => app!.evaluate(() => (globalThis as typeof globalThis & { docxDialogReady?: boolean }).docxDialogReady)).toBe(true)
    await page.evaluate(async id => { const draft = await window.workbench.getDraft(id); if (!draft) throw new Error('Draft unavailable'); await window.workbench.correctDraft({ jobId: id, section: 'experience', index: 0, text: `${draft.content.experience[0].text} Updated while save dialog is open.` }) }, jobId)
    await app.evaluate(() => { (globalThis as typeof globalThis & { resolveDocxDialog?: () => void }).resolveDocxDialog?.(); return true })
    expect(await pendingExport).toMatchObject({ ok: false, cancelled: false, message: expect.stringContaining('changed while choosing') })
    expect(existsSync(staleDestination)).toBe(false)
    expect(await page.evaluate(id => window.workbench.assertDraftExportable(id), jobId)).toMatchObject({ ok: false })
    const regenDraft = page.getByRole('region', { name: 'CV review' })
    await page.getByRole('article', { name: 'Approved CV preview' }).getByRole('button', { name: /Review sources for/ }).first().click()
    await page.getByRole('region', { name: 'Selected wording and sources' }).getByRole('button', { name: 'Suggest different wording' }).click()
    const regenConsent = regenDraft.getByText('What will be shared for this suggestion').locator('..')
    await regenConsent.getByRole('checkbox', { name: /reviewed this bundle/ }).check()
    await regenConsent.getByRole('button', { name: 'Authorize and propose' }).click()
    const comparison = regenDraft.getByRole('region', { name: 'Compare suggestion' })
