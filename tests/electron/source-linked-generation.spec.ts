import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtempSync } from 'node:fs'
import { rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('real Electron UI generates and exposes cited draft with a DEV-only scripted provider', async () => {
  test.setTimeout(90000)
  const userData = mkdtempSync(join(tmpdir(), 'cv-tailor-generation-ui-'))
  let app: Awaited<ReturnType<typeof electron.launch>> | undefined
  try {
    app = await electron.launch({ args: ['.'], timeout: 60000, env: { ...process.env, CV_TAILOR_TEST_USER_DATA_DIR: userData, CV_TAILOR_SCRIPTED_ANALYSIS: 'generation' } })
    let page = await app.firstWindow()
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    await page.getByRole('button', { name: 'My profile' }).click()
    await page.getByLabel('Full name').fill('Zoë Candidate')
    await page.getByLabel('Professional headline').fill('Systems Engineer')
    await page.getByRole('button', { name: 'Save contact details' }).click()
    await page.evaluate(async () => { const contact = (await window.workbench.getProfile()).contact!; return window.workbench.saveContact({ id: contact.id, fullName: contact.fullName, headline: contact.headline, links: [{ label: 'Portfolio', url: 'https://example.test/cv' }] }) })
    expect(await page.evaluate(() => window.workbench.getProfile().then(profile => profile.contact?.links))).toEqual([{ label: 'Portfolio', url: 'https://example.test/cv' }])
    await page.getByRole('navigation', { name: 'Profile sections' }).getByRole('button', { name: 'Skills' }).click()
    await page.getByLabel('Skill name').fill('TypeScript')
    await page.getByRole('button', { name: 'Add skill' }).click()
    await expect(page.getByText('TypeScript', { exact: true })).toBeVisible()
    await page.getByRole('navigation', { name: 'Profile sections' }).getByRole('button', { name: 'Experience' }).click()
    await page.getByRole('button', { name: 'Add role' }).click()
    await page.getByLabel('Role or training title').fill('Senior Engineer')
    await page.getByLabel('Company or institution').fill('Local Systems')
    await page.getByRole('button', { name: 'Start date' }).click()
    await page.getByRole('button', { name: 'Use year only' }).click()
    await page.getByLabel('Original description').fill('Contributed to reliable TypeScript services.')
    await page.getByRole('button', { name: 'Save role' }).click()
    for (let index = 0; index < 25; index++) {
      await page.getByRole('button', { name: 'Add role' }).click()
      await page.getByLabel('Role or training title').fill(`Engineer ${index}`)
      await page.getByLabel('Company or institution').fill(`Systems ${index}`)
      await page.getByRole('button', { name: 'Start date' }).click()
      await page.getByRole('button', { name: 'Use year only' }).click()
      await page.getByLabel('Original description').fill(`Delivered reliable service improvements ${index}.`)
      await page.getByRole('button', { name: 'Save role' }).click()
    }
    await page.getByRole('button', { name: 'Saved jobs' }).click()
    await page.getByLabel('Job title').fill('Fictional Systems Engineer')
    await page.getByLabel('Company').fill('Northwind Labs')
    await page.getByLabel('Job description and requirements').fill('TypeScript and reliable systems experience are required.')
    await page.getByRole('button', { name: 'Save posting' }).click()
    await page.getByRole('button', { name: 'Tailor CV' }).click()
    await page.getByRole('button', { name: 'Inspect outgoing data' }).click()
    const review = page.getByRole('region', { name: 'Outgoing data review' })
    await review.getByRole('checkbox', { name: /I understand the Gemini free-tier data-use terms/ }).check()
    await review.getByRole('button', { name: 'Authorize this run' }).click()
    await review.getByRole('button', { name: 'Analyze posting' }).click()
    await expect(review.getByRole('button', { name: 'Generate tailored draft' })).toBeVisible({ timeout: 60000 })
    await review.getByRole('button', { name: 'Generate tailored draft' }).click()
    await expect(review.getByRole('region', { name: 'Source-linked draft' })).toContainText('Draft · unverified and unapproved', { timeout: 60000 })
    const draft = review.getByRole('region', { name: 'Source-linked draft' })
    await expect(page.getByRole('article', { name: 'Unapproved canonical CV preview' }).getByText('Zoë Candidate')).toBeVisible()
    await expect(page.getByRole('article', { name: 'Unapproved canonical CV preview' }).getByText('Systems Engineer')).toBeVisible()
    await expect(page.getByRole('article', { name: 'Unapproved canonical CV preview' }).getByText('Senior Engineer', { exact: true })).toBeVisible()
    await expect(page.getByRole('article', { name: 'Unapproved canonical CV preview' }).getByText('Local Systems', { exact: true })).toBeVisible()
    await expect(page.getByRole('article', { name: 'Unapproved canonical CV preview' }).getByText(/20\d{2}/).first()).toBeVisible()
    await expect(draft).toContainText('TypeScript')
    await expect(draft).toContainText('Source revision')
    await expect(draft).toContainText('No verification, approval, or export is available yet.')
    const preview = page.getByRole('article', { name: 'Unapproved canonical CV preview' })
    await expect(preview.locator('h2')).toHaveText(['Education', 'Experience', 'Projects', 'Skills', 'Certificates'])
    await expect(review.getByRole('button', { name: /Export|Approve|Verify/ })).toHaveCount(0)
    await page.getByRole('button', { name: 'Measure actual A4 page fit' }).click()
    await expect(page.getByRole('status').filter({ hasText: /Electron PDF:/ })).toContainText(/page/, { timeout: 30000 })
    const report = await page.evaluate(jobId => window.workbench.getDocumentFitReport(jobId), await page.evaluate(() => window.workbench.listJobs().then(jobs => jobs[0].id)))
    expect(report?.actualPages).toBeGreaterThan(0)
    expect(report?.extractedText.join(' ')).toContain('Zoë Candidate')
    expect(report?.linkTargets).toContain('https://example.test/cv')
    const extractedOrder = ['Education', 'Experience', 'Projects', 'Skills', 'Certificates'].map(name => report!.extractedText.findIndex(text => text.includes(name.toUpperCase())))
    expect(extractedOrder.every((position, index) => position >= 0 && (index === 0 || position > extractedOrder[index - 1])), JSON.stringify({ extractedOrder, extractedText: report?.extractedText })).toBe(true)
    expect(report?.targetPages).toBe(1)
    expect(report?.overflow).toBe(true)
    expect(report?.proposedCuts.length).toBeGreaterThan(0)
    const jobId = await page.evaluate(() => window.workbench.listJobs().then(jobs => jobs[0].id))
    const beforeCuts = await page.evaluate(id => window.workbench.getDraft(id), jobId)
    expect(beforeCuts?.revision).toBe(1)
    await page.getByRole('checkbox').first().check()
    await page.getByRole('button', { name: 'Accept selected cuts and create new draft revision' }).click()
    expect(await page.evaluate(id => window.workbench.getDraft(id).then(value => value?.revision), jobId)).toBe(2)
    await expect(page.getByRole('status').filter({ hasText: /Revision 2 · Electron PDF:/ })).toContainText(/page/, { timeout: 30000 })
    await expect.poll(async () => page.evaluate(id => window.workbench.getDocumentFitReport(id).then(value => value?.actualPages), jobId), { timeout: 30000 }).toBeGreaterThan(0)
    const revisedReport = await page.evaluate(id => window.workbench.getDocumentFitReport(id), jobId)
    expect(revisedReport?.actualPages).toBeGreaterThan(0)
    expect(revisedReport?.documentHash).not.toBe(report?.documentHash)
    expect(await page.evaluate(id => window.workbench.getDraft(id).then(value => value?.revision), jobId)).toBe(2)
    const canonical = await page.evaluate(id => window.workbench.getCanonicalDocument(id), jobId)
    expect(canonical?.style).toMatchObject({ fontFamily: 'Arial', bodyPt: 11, pageSize: 'A4' })
    expect(canonical?.identity.links).toEqual([{ label: 'Portfolio', url: 'https://example.test/cv' }])
    const twoPageDraft = await page.evaluate(async id => {
      const consent = await window.workbench.prepareOutboundConsent(id)
      if (!consent.ok) throw new Error(consent.message)
      const accepted = await window.workbench.acceptOutboundConsent(consent.token, true, true)
      if (!accepted.ok) throw new Error(accepted.message)
      await window.workbench.startAnalysis(consent.token)
      return window.workbench.generateDraft(consent.token, 2)
    }, jobId)
    expect(twoPageDraft).toMatchObject({ ok: true, draft: { pageTarget: 2, revision: 3 } })
    const twoPageReport = await page.evaluate(id => window.workbench.measureDocument(id), jobId)
    expect(twoPageReport.targetPages).toBe(2)
    expect(twoPageReport.actualPages).toBeLessThanOrEqual(2)
    await app.close()
    app = await electron.launch({ args: ['.'], timeout: 60000, env: { ...process.env, CV_TAILOR_TEST_USER_DATA_DIR: userData, CV_TAILOR_SCRIPTED_ANALYSIS: 'generation' } })
    page = await app.firstWindow()
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    expect(await page.evaluate(id => window.workbench.getDocumentFitReport(id), jobId)).toEqual(twoPageReport)
  } finally {
    await app?.close().catch(() => {})
    await rm(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 })
  }
})
