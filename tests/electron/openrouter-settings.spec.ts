import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtempSync } from 'node:fs'
import { rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('visible OpenRouter settings save non-secret preferences and explain privacy and credential status', async () => {
  const userData = mkdtempSync(join(tmpdir(), 'cv-tailor-openrouter-'))
  const app = await electron.launch({ args: [join(process.cwd(), 'out/main/index.js')], env: { ...process.env, CV_TAILOR_TEST_USER_DATA_DIR: userData } })
  try {
    const page = await app.firstWindow()
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    await page.getByRole('button', { name: 'Settings' }).click()
    await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible()
    const modelCard = page.getByRole('region', { name: 'Model preference' })
    const apiKeyCard = page.getByRole('region', { name: 'API key' })
    const faithfulnessCard = page.getByRole('region', { name: 'Optional faithfulness review' })
    const [modelBounds, apiKeyBounds, faithfulnessBounds] = await Promise.all([modelCard.boundingBox(), apiKeyCard.boundingBox(), faithfulnessCard.boundingBox()])
    expect(modelBounds).not.toBeNull()
    expect(apiKeyBounds).not.toBeNull()
    expect(faithfulnessBounds).not.toBeNull()
    expect(Math.abs(modelBounds!.y - apiKeyBounds!.y)).toBeLessThan(2)
    expect(faithfulnessBounds!.y).toBeGreaterThan(Math.max(modelBounds!.y + modelBounds!.height, apiKeyBounds!.y + apiKeyBounds!.height))
    expect(faithfulnessBounds!.width).toBeGreaterThan(apiKeyBounds!.width * 1.7)
    const faithfulness = page.getByRole('switch', { name: 'Enable optional faithfulness review for newly authorized runs' })
    await expect(faithfulness).not.toBeChecked()
    await faithfulness.click()
    await expect(faithfulness).toBeChecked()
    await expect(page.getByText('Faithfulness preference saved locally. Existing unresolved findings are not waived.')).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Settings' }).click()
    await expect(page.getByRole('switch', { name: 'Enable optional faithfulness review for newly authorized runs' })).toBeChecked()
    await page.getByRole('switch', { name: 'Enable optional faithfulness review for newly authorized runs' }).click()
    await expect(page.getByRole('switch', { name: 'Enable optional faithfulness review for newly authorized runs' })).not.toBeChecked()
    expect(await page.evaluate(() => window.workbench.getSettings().then(value => value.openRouter.faithfulnessCheck))).toBe(false)
    await expect(page.getByText(/sends requests to third-party model providers/i)).toBeVisible()
    await expect(page.getByText(/LLM check is not proof/i)).toBeVisible()
    await expect(page.getByRole('link', { name: 'OpenRouter privacy policy' })).toHaveAttribute('href', 'https://openrouter.ai/privacy')
    await expect(page.getByRole('textbox', { name: 'OpenRouter model ID' })).toHaveValue('xingchen-agi/xing4.0-29b-a4b:free')
    await expect(page.getByRole('textbox', { name: 'OpenRouter model ID' })).toHaveCSS('border-top-style', 'solid')
    await expect(page.getByRole('spinbutton', { name: 'Minimum spacing (milliseconds)' })).toHaveValue('5000')
    await expect(page.getByRole('spinbutton', { name: 'Attempts per rate window' })).toHaveValue('12')
    await expect(page.getByRole('spinbutton', { name: 'Local daily attempt limit' })).toHaveValue('50')
    await page.getByRole('spinbutton', { name: 'Local daily attempt limit' }).fill('25')
    await page.getByRole('button', { name: 'Save analysis budgets' }).click()
    await expect(page.getByText('Analysis budgets saved locally. No provider request was sent.')).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Settings' }).click()
    await expect(page.getByRole('spinbutton', { name: 'Local daily attempt limit' })).toHaveValue('25')
    await page.getByRole('textbox', { name: 'OpenRouter model ID' }).fill('openai/gpt-4o-mini')
    await page.getByRole('button', { name: 'Save model' }).click()
    await expect(page.getByText(/OpenRouter model saved/)).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: 'Settings' }).click()
    await expect(page.getByRole('textbox', { name: 'OpenRouter model ID' })).toHaveValue('openai/gpt-4o-mini')

    const canary = 'synthetic-openrouter-key-canary'
    await page.getByLabel('OpenRouter API key', { exact: true }).fill(canary)
    await page.getByRole('button', { name: 'Save API key' }).click()
    const stored = page.getByLabel('Saved OpenRouter API key')
    await expect(stored).toHaveAttribute('type', 'password')
    await expect(stored).toHaveValue('stored-openrouter-key')
    await expect(page.locator('.credential-panel')).not.toContainText(canary)
    await page.getByRole('button', { name: 'Reveal key' }).click()
    await expect(stored).toHaveAttribute('type', 'text')
    await expect(stored).toHaveValue(canary)
    await page.getByRole('button', { name: 'Hide key' }).click()
    await expect(stored).toHaveAttribute('type', 'password')
    await expect(stored).toHaveValue('stored-openrouter-key')
    await page.reload()
    await page.getByRole('button', { name: 'Settings' }).click()
    await expect(stored).toHaveAttribute('type', 'password')
    await expect(stored).toHaveValue('stored-openrouter-key')
    await page.clock.install()
    await page.getByRole('button', { name: 'Reveal key' }).click()
    await expect(stored).toHaveValue(canary)
    await page.clock.fastForward(31000)
    await expect(stored).toHaveValue('stored-openrouter-key')
    await page.getByRole('button', { name: 'Copy key' }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Key copied to clipboard' })).toBeVisible()
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(canary)
    const savedSettings = await page.evaluate(() => window.workbench.getSettings())
    expect(savedSettings.openRouter.credential.configured).toBe(true)
    expect(JSON.stringify(savedSettings)).not.toContain(canary)
    await page.getByRole('button', { name: 'Replace key' }).click()
    await expect(page.getByLabel('New OpenRouter API key')).toHaveValue('')
    await page.getByRole('button', { name: 'Cancel replacement' }).click()
    await page.getByRole('button', { name: 'Revoke local key' }).click()
    await expect(page.getByText(/token will still be valid in OpenRouter/i)).toBeVisible()
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(stored).toHaveValue('stored-openrouter-key')
    await page.getByRole('button', { name: 'Revoke local key' }).click()
    await page.getByRole('button', { name: 'Revoke saved key' }).click()
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe('')
    await expect(page.getByText(/removed from this device/i)).toBeVisible()
    await expect(stored).toHaveCount(0)
    const result = await page.evaluate(() => window.workbench.getSettings())
    expect(result.openRouter.credential.configured).toBe(false)
    expect(JSON.stringify(result)).not.toContain('apiKey')
  } finally {
    await app.close()
    await rm(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 })
  }
})
