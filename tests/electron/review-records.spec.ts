import { test, expect, _electron as electron } from '@playwright/test'
import { mkdtempSync } from 'node:fs'
import { rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('review edits whole records with an explicit CV-only or profile scope and exports manual facts', async () => {
  test.setTimeout(240000)
  const userData = mkdtempSync(join(tmpdir(), 'cv-tailor-record-review-'))
  let app: Awaited<ReturnType<typeof electron.launch>> | undefined
  try {
    app = await electron.launch({ args: [join(process.cwd(), 'out/main/index.js')], env: { ...process.env, CV_TAILOR_TEST_USER_DATA_DIR: userData, CV_TAILOR_SCRIPTED_ANALYSIS: 'generation' } })
    const page = await app.firstWindow()
    await page.setViewportSize({ width: 1440, height: 900 })
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    await page.evaluate(async () => {
      await window.workbench.saveContact({ fullName: 'Review Candidate', email: 'candidate@example.test' })
      await window.workbench.saveSkill({ name: 'TypeScript', category: 'Languages' })
      await window.workbench.saveExperience({ kind: 'employment', title: 'Software Engineer', organization: 'Original Systems', description: 'Built TypeScript APIs.', factualItems: [{ text: 'Shipped dependable services.' }] })
    })
    await page.getByRole('button', { name: 'Open saved jobs' }).click()
    await page.getByLabel('Job title').fill('Engineer')
    await page.getByLabel('Company').fill('Example Co')
    await page.getByLabel('Posting and requirements').fill('Build dependable TypeScript services.')
    await page.getByRole('button', { name: 'Save job' }).click()
    await page.getByRole('button', { name: 'Tailor CV', exact: true }).click()
    await page.getByRole('button', { name: 'Inspect outgoing data' }).click()
    const flow = page.getByRole('region', { name: 'Tailoring workflow' })
    await flow.getByRole('checkbox', { name: /reviewed what is sent/i }).check()
    await flow.getByRole('button', { name: 'Authorize this run' }).click()
    await flow.getByRole('button', { name: 'Generate tailored draft' }).click()
    const paper = page.getByRole('article', { name: 'Draft CV review layout' })
    await expect(paper).toBeVisible({ timeout: 45000 })
    const editor = page.getByRole('dialog')
    const declare = async () => editor.getByRole('checkbox', { name: /I confirm these details/i }).check()
    async function selectRecord(name: string) {
      await paper.getByRole('button', { name: `Review sources for ${name}`, exact: true }).first().click()
    }
    await paper.getByRole('button', { name: 'Add skill', exact: true }).click()
    await editor.getByLabel('Skill name').fill('Rust')
    await expect(editor.getByRole('radio', { name: /This CV only/ })).toBeChecked()
    await declare()
    await editor.getByRole('button', { name: 'Save to this CV', exact: true }).click()
    await expect(paper).toContainText('Rust')
    expect((await page.evaluate(() => window.workbench.getProfile())).skills).toEqual(before.profile.skills)
    await expect(page.getByRole('region', { name: 'Review checklist' })).toContainText('Page length needed')
    await selectRecord('Rust')
    await page.getByRole('button', { name: 'Edit record', exact: true }).click()
    await editor.getByLabel('Skill name').fill('Rust tooling')
    await editor.getByRole('radio', { name: /This CV and my profile/ }).check()
    await declare()
    await editor.getByRole('button', { name: 'Save to CV and profile', exact: true }).click()
    await expect(paper).toContainText('Rust tooling')
    expect((await page.evaluate(() => window.workbench.getProfile())).skills.some(skill => skill.name === 'Rust tooling')).toBe(true)
    await selectRecord('Rust tooling')
    await page.getByRole('button', { name: 'Remove record', exact: true }).click()
    await editor.getByRole('button', { name: 'Remove from this CV', exact: true }).click()
    await expect(paper).not.toContainText('Rust tooling')
    expect((await page.evaluate(() => window.workbench.getProfile())).skills.some(skill => skill.name === 'Rust tooling')).toBe(true)

    await paper.getByRole('button', { name: 'Add education', exact: true }).click()
    await editor.getByLabel('Degree', { exact: true }).fill('B.Sc. in Data Science')
    await editor.getByLabel('Institution (optional)').fill('Example University')
    await editor.getByLabel('Start date (optional)').fill('2017')
    await editor.getByLabel('End date (optional)').fill('2021')
    await editor.getByLabel('Details and grade (optional)').fill('CGPA: 3.6 | 2017 - 2021')
    await declare()
    await editor.getByRole('button', { name: 'Save to this CV', exact: true }).click()
    await expect(paper.locator('.paper-grade')).toHaveText('CGPA: 3.6')
    const gradeBox = (await paper.locator('.paper-grade').boundingBox())!, dateBox = (await paper.locator('.paper-entry--education time').boundingBox())!
    expect(gradeBox.y).toBeGreaterThan(dateBox.y)
    expect(Math.abs(gradeBox.x + gradeBox.width - dateBox.x - dateBox.width)).toBeLessThan(3)
    expect((await page.evaluate(() => window.workbench.getProfile())).education).toEqual(before.profile.education)

    await paper.getByRole('button', { name: 'Add experience', exact: true }).click()
    await editor.getByLabel('Job title or role').fill('Research Engineer')
    await editor.getByLabel('Organization', { exact: true }).fill('Model Lab')
    await editor.getByLabel('Experience details').fill('Trained and evaluated machine learning models.')
    await declare()
    await editor.getByRole('button', { name: 'Save to this CV', exact: true }).click()
    await selectRecord('Research Engineer')
    await page.getByRole('button', { name: 'Edit record', exact: true }).click()
    await editor.getByLabel('Job title or role').fill('Machine Learning Engineer')
    await declare()
    await editor.screenshot({ path: 'test-results/review-record-editor.png' })
    await editor.getByRole('button', { name: 'Save to this CV', exact: true }).click()
    await expect(paper).toContainText('Machine Learning Engineer')
    expect((await page.evaluate(() => window.workbench.getExperience())).experience).toEqual(before.experience.experience)

    await paper.getByRole('button', { name: 'Add project', exact: true }).click()
    await editor.getByLabel('Project name').fill('Image classifier')
    await editor.getByLabel('Project details').fill('Evaluated a machine learning image classifier.')
    await editor.getByLabel('Tools and technologies (optional)').fill('Python\nNumPy')
    await editor.getByRole('button', { name: 'Add link', exact: true }).click()
    await editor.getByLabel('URL', { exact: true }).fill('https://github.com/example/classifier')
    await editor.getByRole('radio', { name: /This CV and my profile/ }).check()
    await declare()
    await editor.getByRole('button', { name: 'Save to CV and profile', exact: true }).click()
    await expect(paper.getByRole('link', { name: 'github/classifier' })).toBeVisible()
    await selectRecord('Image classifier')
    await page.getByRole('button', { name: 'Edit record', exact: true }).click()
    await editor.getByLabel('Project name').fill('Classifier service')
    await editor.getByLabel('Tools and technologies (optional)').fill('Python\nPyTorch')
    await editor.getByLabel('URL', { exact: true }).fill('https://github.com/example/classifier-service')
    await editor.getByRole('radio', { name: /This CV and my profile/ }).check()
    await declare()
    await editor.getByRole('button', { name: 'Save to CV and profile', exact: true }).click()
    await expect(paper.getByRole('link', { name: 'github/classifier-service' })).toBeVisible()
    await expect(paper).toContainText('PyTorch')
    expect((await page.evaluate(() => window.workbench.getExperience())).projects.find(item => item.name === 'Classifier service')?.technologies.map(item => item.text)).toEqual(['Python', 'PyTorch'])
    await selectRecord('Classifier service')
    await page.getByRole('button', { name: 'Remove record', exact: true }).click()
    await editor.getByRole('radio', { name: /This CV and my profile/ }).check()
    await expect(editor).toContainText('This also removes the record from My profile')
    await editor.getByRole('button', { name: 'Remove from CV and profile', exact: true }).click()
    await expect(paper).not.toContainText('Classifier service')
    expect((await page.evaluate(() => window.workbench.getExperience())).projects).toHaveLength(0)
    await page.reload()
    await expect(page.locator('[data-ui-ready="true"]')).toBeVisible()
    await page.getByRole('button', { name: 'Engineer Example Co', exact: true }).click()
    await expect(paper).toContainText('Machine Learning Engineer', { timeout: 20000 })
    await expect(paper).toContainText('B.Sc. in Data Science')
    await page.getByRole('button', { name: 'Check CV for issues', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Review checklist' })).toContainText('Checks passed')
    await page.getByRole('button', { name: 'Check page length', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Review checklist' })).toContainText('1 of 1 page', { timeout: 45000 })
    await page.getByRole('checkbox', { name: 'I reviewed this CV and its wording.' }).check()
    await page.getByRole('button', { name: 'Approve CV', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Export approved PDF' })).toBeEnabled({ timeout: 45000 })
    await expect(page.getByRole('img', { name: /Compiled PDF page 1/ })).toBeVisible({ timeout: 45000 })
  } finally {
    await app?.close().catch(() => {})
    await rm(userData, { recursive: true, force: true, maxRetries: 10, retryDelay: 300 })
  }
})
