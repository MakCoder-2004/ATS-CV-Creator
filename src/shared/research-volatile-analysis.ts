import { z } from 'zod'
import { jobResearchIdentitySchema } from './job-research-schema'
import { piModelSelectionSchema } from './pi-model'

const id = z.string().uuid()
const url = z.string().url().max(2048).refine(value => value.startsWith('https://'))

/** Only accepted role evidence is represented here. Company-context findings are excluded. */
export const volatileRoleEvidenceSchema = z.object({
  findingId: id,
  sourceId: id,
  url,
  capturedAt: z.string().datetime({ offset: true }),
  kind: z.enum(['direct-role-text', 'indexed-role-claim']),
  completeness: z.enum(['full', 'partial']),
  text: z.string().min(1).max(16_000),
}).strict()

export const volatileOutgoingSchema = z.object({
  version: z.literal(1),
  researchRunId: id,
  selected: jobResearchIdentitySchema,
  analysisScope: z.enum(['full', 'provisional']),
  unknowns: z.array(z.string().min(1).max(500)).max(32),
  roleEvidence: z.array(volatileRoleEvidenceSchema).min(1).max(48),
}).strict()

export const volatileAnalysisPreviewSchema = z.object({
  token: id,
  expiresAt: z.number().int().nonnegative(),
  selection: piModelSelectionSchema,
  analysisScope: z.enum(['full', 'provisional']),
  /** Exact user-message prompt supplied to the Pi SDK. Its JSON-schema system message is generated by completePiTask. */
  outgoingText: z.string().min(1).max(1_000_000),
  notice: z.string().min(1),
}).strict()
export type VolatileAnalysisPreview = z.infer<typeof volatileAnalysisPreviewSchema>

/** Citations reference accepted finding IDs, not arbitrary URLs or employer context. */
export const volatileAnalysisResponseSchema = z.object({
  requirements: z.array(z.object({
    text: z.string().trim().min(1).max(1000),
    category: z.enum(['responsibility', 'qualification', 'skill', 'experience', 'other']),
    findingIds: z.array(id).min(1).max(48),
  }).strict()).max(80),
}).strict()

export const volatileAnalysisResultSchema = volatileAnalysisResponseSchema.extend({
  researchRunId: id,
  analysisScope: z.enum(['full', 'provisional']),
  unknowns: z.array(z.string().min(1).max(500)).max(32),
  evidence: z.array(volatileRoleEvidenceSchema).min(1).max(48),
  humanReviewRequired: z.literal(true),
}).strict()
export type VolatileAnalysisResult = z.infer<typeof volatileAnalysisResultSchema>

export const volatileAnalysisProgressSchema = z.object({
  token: id,
  status: z.enum(['preview', 'consented', 'preparing', 'dispatched', 'complete', 'uncertain', 'cancelled', 'declined']),
  physicalRequests: z.number().int().min(0).max(1),
  result: volatileAnalysisResultSchema.optional(),
  message: z.string().optional(),
}).strict()
export type VolatileAnalysisProgress = z.infer<typeof volatileAnalysisProgressSchema>
